CREATE TABLE weather_readings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    observed_at TIMESTAMP WITH TIME ZONE NOT NULL,
    fetched_at TIMESTAMP WITH TIME ZONE NOT NULL,
    rain_mm DOUBLE PRECISION NOT NULL CHECK (rain_mm >= 0),
    next_6h_max_probability INTEGER NOT NULL CHECK (next_6h_max_probability BETWEEN 0 AND 100)
);

CREATE INDEX idx_weather_readings_latest ON weather_readings (fetched_at DESC, id DESC);
